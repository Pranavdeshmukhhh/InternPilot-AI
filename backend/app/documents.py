"""Factual, single-column ATS documents and *unverified* resume import.

No candidate facts are generated by a language model.  Imported values are
proposals, never verified profile updates.  PDF output contains only fields the
candidate explicitly verified and can be reproduced without a remote service.
"""
from __future__ import annotations

import io
import re
import zipfile
from pathlib import Path, PurePath
from typing import Any
from xml.sax.saxutils import escape

from docx import Document
from pypdf import PdfReader
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

MAX_UPLOAD_BYTES = 8 * 1024 * 1024
MAX_TEXT_CHARS = 150_000
MAX_PDF_PAGES = 30
_EMAIL = re.compile(r"\b[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]+@[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?\.[A-Za-z]{2,}\b")
_SKILLS = ("Python", "JavaScript", "TypeScript", "Java", "C++", "C#", "SQL", "HTML", "CSS", "React", "Next.js", "Node.js", "FastAPI", "Django", "Flask", "PostgreSQL", "MongoDB", "Redis", "Docker", "Kubernetes", "AWS", "Azure", "Google Cloud", "Git", "TensorFlow", "PyTorch", "scikit-learn", "Pandas", "NumPy", "Machine Learning", "Deep Learning", "Linux")

_FONT_DIR = Path(__file__).parent / "assets" / "fonts"
pdfmetrics.registerFont(TTFont("InternPilotSans", str(_FONT_DIR / "DejaVuSans.ttf")))
pdfmetrics.registerFont(TTFont("InternPilotSans-Bold", str(_FONT_DIR / "DejaVuSans-Bold.ttf")))


def _string(value: Any, limit: int = 4000) -> str:
    if not isinstance(value, (str, int, float)) or isinstance(value, bool):
        return ""
    text = str(value).strip()
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", text)
    return text[:limit]


def _skill_matches(text: str, skill: str) -> bool:
    return bool(re.search(r"(?<![\w+#])" + re.escape(skill) + r"(?![\w+#])", text, re.I))


def parse_resume(content: bytes, filename: str) -> dict:
    """Extract PDF, DOCX or UTF-8 TXT into reviewable proposals.

    The application must obtain explicit verification before using a proposal in
    an application.  Scanned PDFs need an external OCR step and are reported as
    unreadable rather than guessed.  Size and decompression limits apply before
    opening user-controlled input.
    """
    if not content or len(content) > MAX_UPLOAD_BYTES:
        raise ValueError("Resume must contain data and be no larger than 8 MiB.")
    extension = PurePath(filename.replace("\\", "/")).suffix.lower()
    try:
        if extension == ".pdf":
            if not content.startswith(b"%PDF-"):
                raise ValueError("The file does not contain a valid PDF header.")
            reader = PdfReader(io.BytesIO(content), strict=False)
            if reader.is_encrypted:
                raise ValueError("Upload an unencrypted PDF.")
            if len(reader.pages) > MAX_PDF_PAGES:
                raise ValueError("Resume PDF must have no more than 30 pages.")
            chunks: list[str] = []
            char_count = 0
            for page in reader.pages:
                chunk = page.extract_text() or ""
                char_count += len(chunk)
                if char_count > MAX_TEXT_CHARS:
                    raise ValueError("Resume contains too much extracted text.")
                chunks.append(chunk)
            text = "\n".join(chunks)
        elif extension == ".docx":
            with zipfile.ZipFile(io.BytesIO(content)) as archive:
                entries = archive.infolist()
                if len(entries) > 1000 or sum(entry.file_size for entry in entries) > 32 * 1024 * 1024:
                    raise ValueError("DOCX decompressed size exceeds the safe limit.")
                if any(entry.flag_bits & 1 for entry in entries):
                    raise ValueError("Upload an unencrypted DOCX.")
                if "word/document.xml" not in archive.namelist():
                    raise ValueError("The file is not a DOCX document.")
                if any("vbaProject" in entry.filename for entry in entries):
                    raise ValueError("Macro-enabled documents are not accepted.")
            doc = Document(io.BytesIO(content))
            chunks = [paragraph.text for paragraph in doc.paragraphs]
            for table in doc.tables:
                for row in table.rows:
                    chunks.append(" | ".join(cell.text for cell in row.cells))
            text = "\n".join(chunks)
        elif extension == ".txt":
            text = content.decode("utf-8-sig", errors="strict")
        else:
            raise ValueError("Supported resume formats: PDF, DOCX, UTF-8 TXT.")
    except ValueError:
        raise
    except Exception as exc:
        raise ValueError("Could not parse this resume. Upload a readable PDF, DOCX, or UTF-8 TXT.") from exc
    text = _string(text, MAX_TEXT_CHARS + 1)
    if len(text) > MAX_TEXT_CHARS:
        raise ValueError("Resume contains too much extracted text.")
    if not text.strip():
        raise ValueError("No readable text found. Scanned resumes require OCR before upload.")

    proposals: dict[str, Any] = {}
    evidence: dict[str, str] = {}
    match = _EMAIL.search(text)
    if match:
        proposals["email"] = match.group(0)
        evidence["email"] = match.group(0)
    for key, pattern in {
        "github": r"https?://(?:www\.)?github\.com/[A-Za-z0-9_-]+/?",
        "linkedin": r"https?://(?:www\.)?linkedin\.com/in/[A-Za-z0-9_%+-]+/?",
    }.items():
        match = re.search(pattern, text, re.I)
        if match:
            proposals[key] = match.group(0)
            evidence[key] = match.group(0)
    graduation = re.search(
        r"(?:expected\s+(?:graduation|completion)(?:\s+date)?|graduat(?:ion|ing|e)(?:\s+(?:year|date))?)\s*(?:in\s+|[:\-–]\s*)?(?:[A-Za-z]+\s+)?(20\d{2})\b",
        text, re.I,
    )
    if graduation:
        proposals["graduation_year"] = int(graduation.group(1))
        evidence["graduation_year"] = graduation.group(0)
    skills = [skill for skill in _SKILLS if _skill_matches(text, skill)]
    if skills:
        proposals["skills"] = skills
        evidence["skills"] = "Exact case-insensitive terms present in the extracted text; proficiency is unverified."
    return {
        "text": text,
        "proposed_fields": proposals,
        "evidence": evidence,
        "verified": False,
        "verified_fields": [],
        "warnings": ["All extracted fields require your review and explicit verification before use in applications."],
    }


def _verified(profile: dict) -> set[str]:
    values = profile.get("verified_fields", [])
    return {value for value in values if isinstance(value, str)} if isinstance(values, list) else set()


def _required(profile: dict) -> tuple[set[str], str, str]:
    fields = _verified(profile)
    name = _string(profile.get("name"), 150)
    email = _string(profile.get("email"), 254)
    if "name" not in fields or not name:
        raise ValueError("Verify your name in the candidate profile before generating documents.")
    if "email" not in fields or not email or not _EMAIL.fullmatch(email):
        raise ValueError("Verify a valid contact email in the candidate profile before generating documents.")
    return fields, name, email


def _list_strings(value: Any, limit: int = 80) -> list[str]:
    if not isinstance(value, list):
        return []
    return list(dict.fromkeys(item for raw in value[:limit] if (item := _string(raw, 300))))


def _ordered_skills(profile: dict, job: dict) -> list[str]:
    skills = _list_strings(profile.get("skills"))
    context = " ".join([_string(job.get("title")), _string(job.get("description"), 50_000), " ".join(_list_strings(job.get("skills")))])
    return sorted(skills, key=lambda skill: (not _skill_matches(context, skill), skills.index(skill)))


def _entries(profile: dict, field: str, job: dict) -> list[dict]:
    entries = profile.get(field, [])
    if not isinstance(entries, list):
        return []
    valid = [entry for entry in entries[:30] if isinstance(entry, dict)]
    wanted_skills = _list_strings(job.get("skills"))
    context = _string(job.get("title")) + " " + _string(job.get("description"), 50_000)
    if not wanted_skills:
        wanted_skills = [skill for skill in _SKILLS if _skill_matches(context, skill)]
    def relevance(entry: dict) -> int:
        haystack = " ".join(_string(entry.get(key), 8000) for key in ("name", "title", "description"))
        haystack += " " + " ".join(_list_strings(entry.get("skills")))
        return sum(_skill_matches(haystack, skill) for skill in wanted_skills)
    return sorted(valid, key=relevance, reverse=True)


def _render_pdf(lines: list[tuple[str, str]], title: str) -> bytes:
    output = io.BytesIO()
    doc = SimpleDocTemplate(output, pagesize=(8.27 * inch, 11.69 * inch), rightMargin=0.68 * inch, leftMargin=0.68 * inch, topMargin=0.6 * inch, bottomMargin=0.6 * inch, title=title, author="", subject="Verified candidate information", pageCompression=1)
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="CandidateName", fontName="InternPilotSans-Bold", fontSize=19, leading=23, textColor=colors.HexColor("#152c3d"), spaceAfter=8))
    styles.add(ParagraphStyle(name="SectionTitle", fontName="InternPilotSans-Bold", fontSize=10.5, leading=14, textColor=colors.HexColor("#152c3d"), spaceBefore=12, spaceAfter=5, keepWithNext=True))
    styles.add(ParagraphStyle(name="ResumeBody", fontName="InternPilotSans", fontSize=10, leading=14, spaceAfter=5, alignment=TA_LEFT, wordWrap="LTR"))
    styles.add(ParagraphStyle(name="ResumeSubhead", parent=styles["ResumeBody"], fontName="InternPilotSans-Bold", keepWithNext=True))
    story = []
    for kind, text in lines:
        style_name = {"name": "CandidateName", "section": "SectionTitle", "heading": "ResumeSubhead"}.get(kind, "ResumeBody")
        # All input, including job titles, is data; no ReportLab HTML is accepted.
        safe = escape(_string(text, 12000)).replace("\n", "<br/>")
        story.append(Paragraph(safe, styles[style_name]))
    if not story:
        story.append(Spacer(1, 1))
    doc.build(story)
    return output.getvalue()


def _filename(name: str, suffix: str) -> str:
    safe = re.sub(r"[^A-Za-z0-9_-]+", "-", name).strip("-")[:60] or "candidate"
    return f"{safe}-{suffix}.pdf"


def generate_resume(profile: dict, job: dict) -> dict:
    """Tailor order and selection of existing, explicitly verified facts only."""
    fields, name, email = _required(profile)
    used = ["name", "email"]
    lines: list[tuple[str, str]] = [("name", name)]
    contacts = [email]
    for field in ("phone", "country", "github", "linkedin", "portfolio"):
        value = _string(profile.get(field), 500)
        if field in fields and value:
            contacts.append(value)
            used.append(field)
    lines.append(("body", " | ".join(contacts)))
    education = []
    for field in ("degree", "university"):
        value = _string(profile.get(field), 500)
        if field in fields and value:
            education.append(value)
            used.append(field)
    year = profile.get("graduation_year")
    if "graduation_year" in fields and isinstance(year, int) and not isinstance(year, bool) and 1900 <= year <= 2200:
        education.append(f"Expected graduation: {year}")
        used.append("graduation_year")
    if education:
        lines.extend([("section", "EDUCATION"), ("body", " | ".join(education))])
    if "skills" in fields and (skills := _ordered_skills(profile, job)):
        lines.extend([("section", "TECHNICAL SKILLS"), ("body", ", ".join(skills))])
        used.append("skills")
    for field, section in (("projects", "PROJECTS"), ("experience", "EXPERIENCE")):
        if field not in fields:
            continue
        entries = _entries(profile, field, job)
        if not entries:
            continue
        added = False
        for entry in entries:
            heading = _string(entry.get("name" if field == "projects" else "title"), 300)
            organization = _string(entry.get("organization"), 300) if field == "experience" else ""
            description = _string(entry.get("description"), 8000)
            skills = _list_strings(entry.get("skills")) if field == "projects" else []
            if not any((heading, organization, description, skills)):
                continue
            if not added:
                lines.append(("section", section))
                added = True
            if heading or organization:
                lines.append(("heading", " | ".join(value for value in (heading, organization) if value)))
            if description:
                lines.append(("body", description))
            if skills:
                lines.append(("body", "Technologies: " + ", ".join(skills)))
        if added:
            used.append(field)
    text = "\n".join(text for _, text in lines)
    return {"content": _render_pdf(lines, f"{name} - Resume"), "filename": _filename(name, "resume"), "text": text, "used_facts": used}


def generate_cover_letter(profile: dict, job: dict) -> dict:
    """Create a short factual cover letter; no claims beyond verified fields."""
    fields, name, email = _required(profile)
    used = ["name", "email"]
    title = _string(job.get("title"), 300) or "internship opportunity"
    company = _string(job.get("company"), 200)
    lines: list[tuple[str, str]] = [("name", name), ("body", email), ("body", "Dear Hiring Team,"), ("body", f"I am applying for {title}" + (f" at {company}." if company else "."))]
    degree = _string(profile.get("degree"), 250) if "degree" in fields else ""
    university = _string(profile.get("university"), 250) if "university" in fields else ""
    year = profile.get("graduation_year") if "graduation_year" in fields else None
    education = []
    if degree:
        education.append(f"My degree program is {degree}.")
        used.append("degree")
    if university:
        education.append(f"My university is {university}.")
        used.append("university")
    if isinstance(year, int) and not isinstance(year, bool) and 1900 <= year <= 2200:
        education.append(f"My expected graduation year is {year}.")
        used.append("graduation_year")
    if education:
        lines.append(("body", " ".join(education)))
    if "skills" in fields and (skills := _ordered_skills(profile, job)):
        lines.append(("body", "My technical skills include " + ", ".join(skills[:8]) + "."))
        used.append("skills")
    if "projects" in fields:
        entries = _entries(profile, "projects", job)
        project = next((entry for entry in entries if _string(entry.get("name")) and _string(entry.get("description"))), None)
        if project:
            lines.append(("body", f"Project: {_string(project['name'], 300)}. {_string(project['description'], 3000)}"))
            used.append("projects")
    lines.extend([("body", "Thank you for considering my application. I would welcome the opportunity to discuss the role and share more about my work."), ("body", f"Sincerely,\n{name}")])
    text = "\n".join(text for _, text in lines)
    return {"content": _render_pdf(lines, f"{name} - Cover Letter"), "filename": _filename(name, "cover-letter"), "text": text, "used_facts": used}
